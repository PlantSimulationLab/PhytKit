//! `pk agent-files` and `pk skills`: put the agent skill shipped with the Python package into
//! a user's project.
//!
//! The skill (`SKILL.md` and its `references/`) lives inside the installed `phytkit` package;
//! the package tells this module where with `set_skills_dir` when it is imported. The plain
//! `pk` binary built with cargo has no installed skill, so these commands explain that instead.
//!
//! `pk agent-files [DIR]` writes two files:
//! - `AGENTS.md`: facts about the installed version, then the body of `SKILL.md` with its
//!   `references/` links made absolute. The skill is the one source; nothing is a hand copy.
//! - `CLAUDE.md`: only `@AGENTS.md`, so Claude Code reads the same guidance.
//!
//! A file is rewritten only while it starts with the marker line. Once the user deletes that
//! line the file is theirs and is never touched again. `PHYTKIT_AGENT_FILES=0` (or `off`,
//! `false`, `no`, or empty) makes the command write nothing. This is the convention Helios
//! and Phytograph use, so one rule covers all three.

use crate::args::{CliError, ParsedArgs, Result};
use crate::{object, Obj, Output};
use serde_json::{json, Value};
use std::path::{Path, PathBuf};
use std::sync::OnceLock;

pub const MARKER: &str = "<!-- phytkit-managed-file";
pub const ENV_OPT_OUT: &str = "PHYTKIT_AGENT_FILES";
const STAMP: &str = ".phytkit-managed";
const DOCS_URL: &str = "https://plantsimulationlab.github.io/PhytKit/";

static SKILLS_DIR: OnceLock<PathBuf> = OnceLock::new();

/// Called by the Python package on import with `phytkit.skills_dir()`.
pub fn set_skills_dir(dir: PathBuf) {
    let _ = SKILLS_DIR.set(dir);
}

fn marker_line() -> String {
    format!(
        "{MARKER}: regenerated by \"pk agent-files\". Delete this line to keep your own edits. -->"
    )
}

fn skills_dir() -> Result<&'static Path> {
    SKILLS_DIR.get().map(PathBuf::as_path).ok_or_else(|| {
        CliError::usage(
            "not_applicable",
            "This pk was built without the Python package, so it has no agent skill to install.",
        )
        .hint("Install the package (pip install phytkit) and run its pk, or python -m phytkit.")
    })
}

fn posix(p: &Path) -> String {
    p.display().to_string().replace('\\', "/")
}

/// Whether `PHYTKIT_AGENT_FILES` turns the command off.
pub fn disabled_by_env() -> bool {
    std::env::var(ENV_OPT_OUT)
        .map(|v| {
            matches!(
                v.trim().to_lowercase().as_str(),
                "0" | "off" | "false" | "no" | ""
            )
        })
        .unwrap_or(false)
}

fn read_failed(path: &Path, e: std::io::Error) -> CliError {
    CliError::failed(
        "read_failed",
        format!("Couldn't read {}: {e}.", posix(path)),
    )
    .hint("Reinstall phytkit; its agent skill is incomplete.")
}

/// `SKILL.md` without its frontmatter and its first heading, with `references/` links made
/// absolute so they work from any project.
pub fn skill_body(skill: &Path) -> Result<String> {
    let path = skill.join("SKILL.md");
    let text = std::fs::read_to_string(&path).map_err(|e| read_failed(&path, e))?;
    let text = text.replace("\r\n", "\n");
    let body = text
        .strip_prefix("---\n")
        .and_then(|rest| rest.split_once("\n---\n").map(|(_, b)| b))
        .ok_or_else(|| {
            CliError::failed(
                "read_failed",
                format!("{} has no frontmatter.", posix(&path)),
            )
            .hint("Reinstall phytkit; its agent skill is damaged.")
        })?
        .trim_start_matches('\n');
    let body = match body.strip_prefix("# ") {
        Some(rest) => rest
            .split_once('\n')
            .map_or("", |(_, b)| b)
            .trim_start_matches('\n'),
        None => body,
    };
    let refs = posix(&skill.join("references"));
    Ok(body.replace("](references/", &format!("]({refs}/")))
}

/// The managed `AGENTS.md`.
pub fn agents_md() -> Result<String> {
    let dir = skills_dir()?;
    let skill = dir.join("phytkit");
    let v = env!("CARGO_PKG_VERSION");
    let head = [
        marker_line(),
        String::new(),
        "# Using PhytKit (the phytkit Python package and its pk command)".into(),
        String::new(),
        format!("- Installed: `phytkit` {v}."),
        format!(
            "- The agent skill for this version, with its reference files: `{}`.",
            posix(&skill.join("SKILL.md"))
        ),
        format!(
            "- If `python -c \"import phytkit; print(phytkit.__version__)\"` prints something other than {v}, run `pk agent-files` again: this file describes {v}."
        ),
        "- `pk describe` lists every model, parameter (with units and bounds), option, error code and warning code of the installed version. Trust it over this file, over the online docs, and over memory.".into(),
        format!("- Online documentation, for background: {DOCS_URL}"),
        String::new(),
    ];
    Ok(head.join("\n") + "\n" + skill_body(&skill)?.trim_end_matches('\n') + "\n")
}

pub fn claude_md() -> String {
    format!("{}\n\n@AGENTS.md\n", marker_line())
}

/// Writes `content` to `path` unless the file is the user's own. Returns the status.
fn write_managed(path: &Path, content: &str, dry_run: bool) -> Result<&'static str> {
    if path.exists() {
        let existing = std::fs::read(path).map_err(|e| read_failed(path, e))?;
        if !existing.starts_with(MARKER.as_bytes()) {
            return Ok("user-owned");
        }
        if existing == content.as_bytes() {
            return Ok("unchanged");
        }
    }
    if dry_run {
        return Ok("would be written");
    }
    std::fs::write(path, content).map_err(|e| {
        CliError::failed(
            "write_failed",
            format!("Couldn't write {}: {e}.", posix(path)),
        )
        .hint("Check that the folder is writable.")
    })?;
    Ok("written")
}

fn folder(raw: &str) -> Result<PathBuf> {
    let p = PathBuf::from(raw);
    if !p.exists() {
        return Err(
            CliError::failed("file_not_found", format!("Folder \"{raw}\" doesn't exist."))
                .hint("Give the project's folder, or run pk agent-files from inside it."),
        );
    }
    if !p.is_dir() {
        return Err(CliError::usage(
            "invalid_value",
            format!("\"{raw}\" is a file, not a folder."),
        )
        .hint("Give the project's folder."));
    }
    Ok(std::fs::canonicalize(&p).unwrap_or(p))
}

pub fn agent_files(args: &ParsedArgs) -> Result<Output> {
    if args.bool("stdout", false) {
        return Ok(Output::Raw(agents_md()?));
    }
    let raw = args.positional.first().map(String::as_str).unwrap_or(".");
    let dir = folder(raw)?;
    if disabled_by_env() {
        return Ok(Output::Json(object(json!({
            "dir": posix(&dir),
            "disabled": true,
            "files": [],
            "notes": [format!("{ENV_OPT_OUT} turns pk agent-files off; nothing was written.")]
        }))));
    }
    let dry_run = args.bool("dry-run", false);
    let agents = write_managed(&dir.join("AGENTS.md"), &agents_md()?, dry_run)?;
    let claude = write_managed(&dir.join("CLAUDE.md"), &claude_md(), dry_run)?;
    let mut notes: Vec<String> = Vec::new();
    if claude == "user-owned" && agents != "user-owned" {
        let own = std::fs::read_to_string(dir.join("CLAUDE.md")).unwrap_or_default();
        if !own.contains("@AGENTS.md") {
            notes.push(format!(
                "{} is your own file, so Claude Code will not read AGENTS.md. Add the line @AGENTS.md to it.",
                posix(&dir.join("CLAUDE.md"))
            ));
        }
    }
    if agents == "user-owned" {
        notes.push(format!(
            "{} is your own file (it doesn't start with the marker line), so it was left alone. Delete it, or paste in the output of pk agent-files --stdout, to update it.",
            posix(&dir.join("AGENTS.md"))
        ));
    }
    let file = |name: &str, status: &str| json!({ "name": name, "path": posix(&dir.join(name)), "status": status });
    Ok(Output::Json(object(json!({
        "dir": posix(&dir),
        "disabled": false,
        "files": [file("AGENTS.md", agents), file("CLAUDE.md", claude)],
        "notes": notes
    }))))
}

pub fn skills_path(_args: &ParsedArgs) -> Result<Output> {
    let dir = skills_dir()?;
    Ok(Output::Json(object(json!({
        "path": posix(dir),
        "skill": posix(&dir.join("phytkit").join("SKILL.md")),
        "version": env!("CARGO_PKG_VERSION")
    }))))
}

fn copy_tree(from: &Path, to: &Path) -> std::io::Result<()> {
    std::fs::create_dir_all(to)?;
    for e in std::fs::read_dir(from)? {
        let e = e?;
        let name = e.file_name();
        let n = name.to_string_lossy();
        if n.starts_with('.') || n == "__pycache__" {
            continue;
        }
        let (src, dst) = (e.path(), to.join(&name));
        if src.is_dir() {
            copy_tree(&src, &dst)?;
        } else {
            std::fs::copy(&src, &dst)?;
        }
    }
    Ok(())
}

pub fn skills_install(args: &ParsedArgs) -> Result<Output> {
    let src_root = skills_dir()?;
    let dest = PathBuf::from(args.str("to")?.unwrap_or_else(|| ".claude/skills".into()));
    let force = args.bool("force", false);
    let write_err = |p: &Path, e: std::io::Error| {
        CliError::failed("write_failed", format!("Couldn't write {}: {e}.", posix(p)))
            .hint("Check that the folder is writable.")
    };
    let mut skills: Vec<Value> = Vec::new();
    let mut entries: Vec<PathBuf> = std::fs::read_dir(src_root)
        .map_err(|e| read_failed(src_root, e))?
        .filter_map(|e| e.ok().map(|e| e.path()))
        .filter(|p| p.join("SKILL.md").is_file())
        .collect();
    entries.sort();
    for src in entries {
        let name = src.file_name().unwrap().to_string_lossy().to_string();
        let target = dest.join(&name);
        let status = if target.exists() {
            if !target.join(STAMP).is_file() && !force {
                return Err(CliError::failed(
                    "already_exists",
                    format!(
                        "{} exists and wasn't installed by pk skills install.",
                        posix(&target)
                    ),
                )
                .hint("Remove it, or pass --force to replace it."));
            }
            std::fs::remove_dir_all(&target).map_err(|e| write_err(&target, e))?;
            "replaced"
        } else {
            "installed"
        };
        copy_tree(&src, &target).map_err(|e| write_err(&target, e))?;
        std::fs::write(
            target.join(STAMP),
            format!(
                "phytkit {}: installed by \"pk skills install\". Run it again after upgrading phytkit. Delete this file to keep your own edits.\n",
                env!("CARGO_PKG_VERSION")
            ),
        )
        .map_err(|e| write_err(&target, e))?;
        let path = std::fs::canonicalize(&target).unwrap_or(target);
        skills.push(json!({ "name": name, "path": posix(&path), "status": status }));
    }
    let out: Obj = object(json!({ "to": posix(&dest), "skills": skills }));
    Ok(Output::Json(out))
}
